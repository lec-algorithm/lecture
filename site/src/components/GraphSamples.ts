// 찍을 때만 소수로 바꾼다(scale: 100).

export interface GraphSample {
  /** 정점 좌표. 번호가 곧 배열 인덱스다. */
  nodes: [number, number][];
  /** [u, v] 또는 [u, v, w] */
  edges: number[][];
  directed?: boolean;
  /** 가중치를 이 값으로 나눠 찍는다(0.16처럼). 없으면 정수 그대로 */
  scale?: number;
  /** 정점 이름 대신 쓸 글자 (없으면 번호) */
  labels?: string[];
}

